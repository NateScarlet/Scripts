
<#
.SYNOPSIS
    iroh-relay 安装向导（Windows，Tailscale IP 直连模式）
.DESCRIPTION
    在 Windows 上安装 iroh-relay，绑定 Tailscale 虚拟 IP（100.x），
    仅 tailnet 内设备可达，不依赖 DNS 解析，不占用 443 端口。
    使用 WinSW 注册为 Windows 服务。所有交互信息在运行时询问。
.NOTES
    选择 IP 直连而非域名 + Tailscale Serve 的原因：
    iroh 客户端自带 DNS 解析器，不读 Windows hosts 与 NRPT，
    直查上游 nameserver，导致 *.ts.net 域名在非 MagicDNS 环境解析失败。
#>

[CmdletBinding()]
param(
    [string]$InstallDir = "$env:ProgramData\iroh-relay",
    [string]$RelayVersion = "1.4.1",
    [int]$RelayPort = 3340,
    # 仅供自动化测试：只加载函数，不进入主流程
    [switch]$SkipMain
)

$ErrorActionPreference = 'Stop'

# ===================== 生成逻辑（可单测） =====================

function New-RelayToken {
    # 64 位小写十六进制令牌（32 字节随机），与 UniClipboard 官方 openssl rand -hex 32 一致
    $bytes = [System.Security.Cryptography.RandomNumberGenerator]::GetBytes(32)
    return [Convert]::ToHexString($bytes).ToLower()
}

function New-RelayConfigContent {
    param(
        [Parameter(Mandatory)][string]$BindAddress,
        [Parameter(Mandatory)][int]$Port,
        [Parameter(Mandatory)][string]$Token
    )
    # Token 必填：绑定 Tailscale IP 后已脱离域名边界，靠令牌控制准入
    $lines = @()
    $lines += "# iroh-relay configuration (generated by wizard)"
    $lines += "enable_relay = true"
    $lines += "http_bind_addr = `"$BindAddress`:$Port`""
    $lines += "enable_quic_addr_discovery = false"
    $lines += "enable_metrics = false"
    $lines += ""
    $lines += "[access]"
    $lines += "shared_token = [`"$Token`"]"
    return ($lines -join "`n")
}

function New-WinswServiceXml {
    param(
        [Parameter(Mandatory)][string]$ServiceId,
        [Parameter(Mandatory)][string]$BinaryPath,
        [Parameter(Mandatory)][string]$ConfigPath,
        [Parameter(Mandatory)][string]$WorkingDirectory,
        [Parameter(Mandatory)][string]$LogDirectory
    )
    # XML 特殊字符需转义，路径中的 & < > 必须处理
    $esc = { param($s) [System.Security.SecurityElement]::Escape($s) }
    return @"
<service>
  <id>$(& $esc $ServiceId)</id>
  <name>iroh-relay</name>
  <description>iroh relay server bound to Tailscale IP</description>
  <executable>$(& $esc $BinaryPath)</executable>
  <arguments>--config-path "$(& $esc $ConfigPath)"</arguments>
  <workingdirectory>$(& $esc $WorkingDirectory)</workingdirectory>
  <logpath>$(& $esc $LogDirectory)</logpath>
  <log mode="roll-by-size">
    <sizeThreshold>1048576</sizeThreshold>
    <keepFiles>5</keepFiles>
  </log>
  <onfailure action="restart" delay="30 sec"/>
  <resetfailure>1 hour</resetfailure>
  <startmode>Automatic</startmode>
</service>
"@
}

# ===================== UI 辅助 =====================

function Write-Stage {
    param([int]$Number, [int]$Total, [string]$Title)
    Clear-Host
    Write-Host ""
    Write-Host ("=" * 62) -ForegroundColor Cyan
    Write-Host ("  Stage {0}/{1}: {2}" -f $Number, $Total, $Title) -ForegroundColor Cyan
    Write-Host ("=" * 62) -ForegroundColor Cyan
    Write-Host ""
}

function Read-Value {
    param([string]$Prompt, [string]$Default)
    if ($Default) {
        $val = Read-Host -Prompt "$Prompt [$Default]"
        if ([string]::IsNullOrWhiteSpace($val)) { return $Default }
        return $val.Trim()
    }
    return (Read-Host -Prompt $Prompt).Trim()
}

function Confirm-Step {
    param([string]$Message)
    $ans = Read-Host -Prompt "$Message (y/N)"
    return $ans -match '^[yY]'
}

function Pause-Step {
    Read-Host -Prompt "按 Enter 继续..." | Out-Null
}

function Test-Admin {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    $p = [Security.Principal.WindowsPrincipal]$id
    return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Get-TailscaleIPv4 {
    # 取本机 Tailscale IPv4；多网卡场景下取第一个 100.x 地址
    $out = & tailscale ip -4 2>$null
    if ($LASTEXITCODE -ne 0 -or -not $out) { return $null }
    return @($out)[0].Trim()
}

if ($SkipMain) { return }

# ===================== 主流程 =====================

$TotalStages = 6
$BinaryName  = "iroh-relay.exe"
$ConfigName  = "iroh-relay.toml"
$ServiceName = "iroh-relay"
$WinSWName   = "iroh-relay-service.exe"

# ------------------- Stage 1: 环境检查 -------------------
Write-Stage 1 $TotalStages "环境检查"

if (-not (Test-Admin)) {
    Write-Host "  ✗ 需要管理员权限（安装 Windows 服务、读取 Tailscale 状态）。" -ForegroundColor Red
    Write-Host "    请右键 PowerShell -> 以管理员身份运行，重新执行本脚本。" -ForegroundColor Yellow
    exit 1
}
Write-Host "  ✓ 管理员权限已确认。" -ForegroundColor Green

$tsCmd = Get-Command tailscale -ErrorAction SilentlyContinue
if (-not $tsCmd) {
    Write-Host "  ✗ 未找到 tailscale 命令。请先安装并登录 Tailscale。" -ForegroundColor Red
    exit 1
}
Write-Host "  ✓ Tailscale 已安装: $($tsCmd.Source)" -ForegroundColor Green

# gh 用于下载 iroh-relay 与 WinSW，缺失时无法继续
$ghCmd = Get-Command gh -ErrorAction SilentlyContinue
if (-not $ghCmd) {
    Write-Host "  ✗ 未找到 gh（GitHub CLI），无法下载 iroh-relay 与 WinSW。" -ForegroundColor Red
    Write-Host "    请先安装 gh 并执行 gh auth login。" -ForegroundColor Yellow
    exit 1
}
Write-Host "  ✓ GitHub CLI 已就绪: $($ghCmd.Source)" -ForegroundColor Green

$tsIp = Get-TailscaleIPv4
if (-not $tsIp) {
    Write-Host "  ✗ 无法读取 Tailscale IPv4（可能未登录或未连接）。" -ForegroundColor Red
    Write-Host "    请先运行 tailscale up 并确认 tailscale ip -4 有输出。" -ForegroundColor Yellow
    exit 1
}
$tsIp = Read-Value "relay 绑定的 Tailscale IP" $tsIp
Write-Host "  ✓ 将绑定: ${tsIp}:$RelayPort" -ForegroundColor Green
Write-Host "    注意：该地址仅同一 tailnet 内设备可达；IP 变化后需重跑本脚本。" -ForegroundColor Gray

if (-not (Test-Path $InstallDir)) {
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
}
Write-Host "  ✓ 安装目录: $InstallDir" -ForegroundColor Green
Pause-Step

# ------------------- Stage 2: 获取 iroh-relay -------------------
Write-Stage 2 $TotalStages "获取 iroh-relay 二进制"

$binaryPath = Join-Path $InstallDir $BinaryName
$skipDownload = $false
if (Test-Path $binaryPath) {
    Write-Host "  ✓ 已存在: $binaryPath" -ForegroundColor Green
    if (-not (Confirm-Step "重新下载并覆盖？")) { $skipDownload = $true }
}
if (-not $skipDownload) {
    $RelayVersion = (Read-Value "iroh-relay 版本" $RelayVersion).TrimStart('v')
    $asset = "iroh-relay-v$RelayVersion-x86_64-pc-windows-msvc.zip"
    Write-Host "  下载 $asset ..." -ForegroundColor Yellow
    & gh release download "v$RelayVersion" --repo n0-computer/iroh --pattern $asset --dir $InstallDir --clobber
    $zipPath = Join-Path $InstallDir $asset
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $zipPath)) {
        Write-Host "  ✗ 下载失败。可手动下载后解压到 $InstallDir ：" -ForegroundColor Red
        Write-Host "    https://github.com/n0-computer/iroh/releases/download/v$RelayVersion/$asset" -ForegroundColor Yellow
        exit 1
    }
    Expand-Archive -Path $zipPath -DestinationPath $InstallDir -Force
    Remove-Item $zipPath -Force -ErrorAction SilentlyContinue
    if (-not (Test-Path $binaryPath)) {
        $found = Get-ChildItem -Path $InstallDir -Filter $BinaryName -Recurse -ErrorAction SilentlyContinue | Select-Object -First 1
        if (-not $found) { Write-Host "  ✗ 压缩包内未找到 $BinaryName" -ForegroundColor Red; exit 1 }
        Copy-Item $found.FullName $binaryPath -Force
    }
}
Write-Host "  ✓ 二进制就绪: $binaryPath" -ForegroundColor Green
Pause-Step

# ------------------- Stage 3: 生成配置 -------------------
Write-Stage 3 $TotalStages "生成配置"

Write-Host "  relay 将监听 ${tsIp}:$RelayPort（Tailscale 虚拟网卡）。" -ForegroundColor Gray
Write-Host "  明文 HTTP，但流量走 WireGuard 加密隧道，仅 tailnet 内设备可达。" -ForegroundColor Gray
Write-Host "  不配置 [tls] 段，不依赖 DNS 解析。" -ForegroundColor Gray
Write-Host ""
$token = New-RelayToken
Write-Host "  ✓ 已生成访问令牌（必填，用于控制 relay 准入）。" -ForegroundColor Green

$configPath = Join-Path $InstallDir $ConfigName
$content = New-RelayConfigContent -BindAddress $tsIp -Port $RelayPort -Token $token
Set-Content -Path $configPath -Value $content -Encoding UTF8
Write-Host "  ✓ 配置已写入: $configPath" -ForegroundColor Green
Write-Host "    预览（令牌已隐去）：" -ForegroundColor Gray
$preview = $content -replace [regex]::Escape($token), '<token>'
Write-Host ("      " + ($preview -replace "`n", "`n      ")) -ForegroundColor DarkGray
Pause-Step

# ------------------- Stage 4: 防火墙规则 -------------------
Write-Stage 4 $TotalStages "配置防火墙规则"

$fwRuleName = "iroh-relay (Tailscale IP)"
$existingRule = Get-NetFirewallRule -DisplayName $fwRuleName -ErrorAction SilentlyContinue
if ($existingRule) {
    Write-Host "  ✓ 防火墙规则已存在: $fwRuleName" -ForegroundColor Green
} else {
    if (Confirm-Step "为 ${RelayPort}/tcp 添加仅限 Tailscale 网段的入站规则？") {
        # 100.64.0.0/10 是 Tailscale 使用的 CGNAT 网段
        New-NetFirewallRule -DisplayName $fwRuleName -Direction Inbound -Action Allow `
            -Protocol TCP -LocalPort $RelayPort -RemoteAddress 100.64.0.0/10 | Out-Null
        Write-Host "  ✓ 已添加防火墙规则（仅 100.64.0.0/10 可入）。" -ForegroundColor Green
    } else {
        Write-Host "  已跳过防火墙规则。若其他设备连不上，请检查防火墙。" -ForegroundColor Yellow
    }
}
Pause-Step

# ------------------- Stage 5: 注册 Windows 服务 -------------------
Write-Stage 5 $TotalStages "注册 Windows 服务（WinSW）"

$winswPath = Join-Path $InstallDir $WinSWName
if (-not (Test-Path $winswPath)) {
    Write-Host "  下载 WinSW ..." -ForegroundColor Yellow
    & gh release download v2.12.0 --repo winsw/winsw --pattern "WinSW-x64.exe" --dir $InstallDir --clobber
    $downloaded = Join-Path $InstallDir "WinSW-x64.exe"
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $downloaded)) {
        Write-Host "  ✗ WinSW 下载失败。请手动下载 WinSW-x64.exe 到: $winswPath" -ForegroundColor Red
        exit 1
    }
    Move-Item $downloaded $winswPath -Force
}
Write-Host "  ✓ WinSW 就绪: $winswPath" -ForegroundColor Green

# WinSW v2 只按「exe 基名 + .xml」查找配置，必须同名同目录
$winswBaseName = [System.IO.Path]::GetFileNameWithoutExtension($WinSWName)
$xmlPath = Join-Path $InstallDir "$winswBaseName.xml"
$logDir  = Join-Path $InstallDir "logs"
if (-not (Test-Path $logDir)) { New-Item -ItemType Directory -Path $logDir -Force | Out-Null }
New-WinswServiceXml -ServiceId $ServiceName -BinaryPath $binaryPath -ConfigPath $configPath `
    -WorkingDirectory $InstallDir -LogDirectory $logDir |
    Set-Content -Path $xmlPath -Encoding UTF8

$svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
if ($svc) {
    Write-Host "  发现已有服务，先停止并卸载..." -ForegroundColor Yellow
    Stop-Service -Name $ServiceName -Force -ErrorAction SilentlyContinue
    & $winswPath uninstall
    Start-Sleep -Seconds 2
}

Write-Host "  安装服务..." -ForegroundColor Yellow
& $winswPath install
if ($LASTEXITCODE -ne 0) { Write-Host "  ✗ 服务安装失败。" -ForegroundColor Red; exit 1 }
& $winswPath start
Start-Sleep -Seconds 3
$svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
if ($svc -and $svc.Status -eq 'Running') {
    Write-Host "  ✓ 服务已启动: $ServiceName" -ForegroundColor Green
} else {
    Write-Host "  ⚠ 服务状态异常: $($svc.Status)。请查看日志: $logDir" -ForegroundColor Yellow
}
Pause-Step

# ------------------- Stage 6: 验证与收尾 -------------------
Write-Stage 6 $TotalStages "验证与收尾"

$relayUrl = "http://${tsIp}:$RelayPort"
Write-Host "  等待服务就绪..." -ForegroundColor Gray
Start-Sleep -Seconds 3
$probeOk = $false
try {
    $resp = Invoke-WebRequest -Uri "$relayUrl/" -UseBasicParsing -TimeoutSec 10 -ErrorAction Stop
    if ($resp.StatusCode -eq 200) { $probeOk = $true }
} catch {
    Write-Host "  探测失败: $($_.Exception.Message)" -ForegroundColor DarkYellow
}
if ($probeOk) {
    Write-Host "  ✓ $relayUrl 返回 200" -ForegroundColor Green
} else {
    Write-Host "  ⚠ 无法通过 $relayUrl 访问 relay。" -ForegroundColor Yellow
    Write-Host "    检查: Get-Service $ServiceName；日志: $logDir" -ForegroundColor Gray
}

Clear-Host
Write-Host ("=" * 62) -ForegroundColor Green
Write-Host "  ✓ iroh-relay 安装完成" -ForegroundColor Green
Write-Host ("=" * 62) -ForegroundColor Green
Write-Host ""
Write-Host "  UniClipboard 中继地址:" -ForegroundColor Cyan
Write-Host "    $relayUrl" -ForegroundColor White
Write-Host ""
Write-Host "  访问令牌:" -ForegroundColor Cyan
Write-Host "    $token" -ForegroundColor White
Write-Host "    （每台设备都需在自定义中继配置中填入）" -ForegroundColor Gray
Write-Host ""
Write-Host "  配置文件: $configPath" -ForegroundColor Gray
Write-Host "  服务名称: $ServiceName" -ForegroundColor Gray
Write-Host "  服务日志: $logDir" -ForegroundColor Gray
Write-Host ""
Write-Host "  重要说明:" -ForegroundColor Cyan
Write-Host "    - 该地址仅同一 tailnet 内设备可达，公网无法路由到 100.x。" -ForegroundColor Gray
Write-Host "    - 服务随系统启动；若开机时 Tailscale 尚未就绪，WinSW 会每 30 秒重试。" -ForegroundColor Gray
Write-Host "    - 若本机 Tailscale IP 变更，需重跑本向导更新配置。" -ForegroundColor Gray
Write-Host ""
